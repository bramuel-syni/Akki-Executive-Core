#!/usr/bin/env python3
"""Phase 5 Part B — Per-context OpenAPI SDK slice generator.

Walks the live `app.openapi()` document and writes three self-contained
slice files, one per bounded context:

    /app/backend/openapi-sdk/synisense.openapi.json
    /app/backend/openapi-sdk/solva.openapi.json
    /app/backend/openapi-sdk/akki.openapi.json

Each slice:
  • Keeps only paths under `/v1/<context>/*`.
  • Inlines every `components.schemas` referenced (directly or
    transitively) by the kept paths so the slice is self-contained.
  • Re-emits `info.title` as `<Context> API` and `info.version` as `1.0`.
  • Validates as OpenAPI 3.1 (passes `openapi-spec-validator` if
    installed; light internal schema-walking validation otherwise).

Usage:
    python scripts/generate_sdk_slices.py [--check]

Flags:
  --check   Don't write — fail with non-zero exit if the on-disk slice
            files diverge from what would be generated now. This is the
            invariant-test hook used by `tests/invariants/`.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Set


CONTEXTS = ("synisense", "solva", "akki")
SLICE_DIR = Path(__file__).resolve().parents[1] / "openapi-sdk"


def _gather_refs(node: Any, found: Set[str]) -> None:
    """Walk a JSON-shaped subtree collecting every `$ref` schema name."""
    if isinstance(node, dict):
        if "$ref" in node and isinstance(node["$ref"], str):
            ref = node["$ref"]
            if ref.startswith("#/components/schemas/"):
                found.add(ref.rsplit("/", 1)[-1])
        for v in node.values():
            _gather_refs(v, found)
    elif isinstance(node, list):
        for v in node:
            _gather_refs(v, found)


def _resolve_transitive_schemas(
    schemas: Dict[str, Any], seed: Set[str]
) -> Set[str]:
    """Given a seed set of schema names, find every transitively-referenced one."""
    closed: Set[str] = set()
    todo: List[str] = list(seed)
    while todo:
        name = todo.pop()
        if name in closed:
            continue
        closed.add(name)
        schema = schemas.get(name)
        if schema is None:
            continue
        new_refs: Set[str] = set()
        _gather_refs(schema, new_refs)
        for r in new_refs:
            if r not in closed:
                todo.append(r)
    return closed


def _build_slice(spec: Dict[str, Any], context: str) -> Dict[str, Any]:
    """Build the per-context OpenAPI slice document."""
    paths_in: Dict[str, Any] = spec.get("paths", {}) or {}
    prefix = f"/v1/{context}/"
    kept_paths: Dict[str, Any] = {
        p: op for p, op in paths_in.items() if p.startswith(prefix)
    }

    # Gather every schema reference reachable from the kept paths.
    seed_refs: Set[str] = set()
    _gather_refs(kept_paths, seed_refs)

    components_in = (spec.get("components") or {})
    schemas_in: Dict[str, Any] = components_in.get("schemas", {}) or {}
    kept_schema_names = _resolve_transitive_schemas(schemas_in, seed_refs)
    kept_schemas: Dict[str, Any] = {
        n: schemas_in[n] for n in sorted(kept_schema_names) if n in schemas_in
    }

    # Keep `securitySchemes` verbatim so partner-SDK auth resolves.
    kept_security = components_in.get("securitySchemes", {}) or {}

    return {
        "openapi": spec.get("openapi", "3.1.0"),
        "info": {
            "title": f"{context.capitalize()} API",
            "version": "1.0",
            "description": (
                f"Versioned `/v1/{context}/*` SDK surface for the "
                f"{context.capitalize()} bounded context.\n\n"
                f"Generated by `scripts/generate_sdk_slices.py` against "
                f"the live OpenAPI document at Phase 5 close. See "
                f"`/app/memory/API_VERSIONING.md` for the versioning "
                f"contract."
            ),
        },
        "paths": dict(sorted(kept_paths.items())),
        "components": {
            "schemas": kept_schemas,
            **({"securitySchemes": kept_security} if kept_security else {}),
        },
    }


def _light_validate(slice_doc: Dict[str, Any], context: str) -> List[str]:
    """Internal validation when openapi-spec-validator isn't installed.

    Surfaces only the cheap wire-shape failures (missing required
    top-level keys, dangling refs after slicing). Heavy linting is
    delegated to the formal validator when present.
    """
    errors: List[str] = []
    for required in ("openapi", "info", "paths", "components"):
        if required not in slice_doc:
            errors.append(f"missing top-level key: {required}")
    if "version" not in slice_doc.get("info", {}):
        errors.append("info.version missing")
    schemas = slice_doc.get("components", {}).get("schemas", {})
    # Dangling-ref scan: every $ref into components.schemas must resolve.
    refs: Set[str] = set()
    _gather_refs(slice_doc, refs)
    for ref in refs:
        if ref not in schemas:
            errors.append(f"dangling $ref to components.schemas/{ref}")
    # Each kept path must start with /v1/<context>/
    for p in slice_doc.get("paths", {}).keys():
        if not p.startswith(f"/v1/{context}/"):
            errors.append(f"path outside /v1/{context}/ slice: {p}")
    return errors


def _try_strict_validate(slice_doc: Dict[str, Any]) -> List[str]:
    """If `openapi-spec-validator` is installed, run strict validation."""
    try:
        from openapi_spec_validator import validate_spec  # type: ignore
    except ImportError:
        return []
    try:
        validate_spec(slice_doc)
        return []
    except Exception as exc:  # pragma: no cover — surface as test failure
        return [f"openapi-spec-validator: {exc}"]


def _load_live_spec() -> Dict[str, Any]:
    # Server import is heavy — defer until invoked. Loading sets up Mongo
    # client etc., but the openapi document itself is purely declarative.
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from server import app  # noqa: E402
    return app.openapi()


def generate(check: bool = False) -> int:
    spec = _load_live_spec()
    SLICE_DIR.mkdir(parents=True, exist_ok=True)

    drift: List[str] = []
    for ctx in CONTEXTS:
        slice_doc = _build_slice(spec, ctx)
        errors = _light_validate(slice_doc, ctx) + _try_strict_validate(slice_doc)
        if errors:
            print(f"VALIDATION ERRORS for {ctx}:")
            for e in errors:
                print(f"  - {e}")
            return 2

        target = SLICE_DIR / f"{ctx}.openapi.json"
        new_text = json.dumps(slice_doc, indent=2, sort_keys=True) + "\n"
        if check:
            if not target.exists():
                drift.append(f"{target.name}: missing on disk")
                continue
            on_disk = target.read_text()
            if on_disk != new_text:
                drift.append(
                    f"{target.name}: drift between disk and live OpenAPI "
                    f"(disk_len={len(on_disk)}, new_len={len(new_text)})"
                )
        else:
            target.write_text(new_text)
            print(
                f"wrote {target} ({len(slice_doc['paths'])} paths, "
                f"{len(slice_doc['components']['schemas'])} schemas)"
            )

    if check:
        if drift:
            print("DRIFT DETECTED:")
            for d in drift:
                print(f"  - {d}")
            print(
                "Run `python scripts/generate_sdk_slices.py` to refresh "
                "the slice files."
            )
            return 1
        print("OK — all slice files match the live OpenAPI document.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Don't write; fail with non-zero if on-disk slices diverge.",
    )
    args = parser.parse_args()
    return generate(check=args.check)


if __name__ == "__main__":
    sys.exit(main())
